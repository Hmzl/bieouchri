export const DICTS = { fr, ar }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const plural = vars && typeof vars.n === 'number' && vars.n > 1 ? `${key}_plural` : key
  let text = DICTS[lang][plural] ?? DICTS[lang][key] ?? DICTS.fr[plural] ?? DICTS.fr[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

export function categoryLabel(lang: Lang, name: string): string {
  const key = `cat.${name}`
  const text = translate(lang, key)
  return text === key ? name : text
}

export function mapError(lang: Lang, message: string): string {
  if (message.startsWith('err.stock:')) {
    return translate(lang, 'err.stock', { name: message.slice('err.stock:'.length) })
  }
  const text = translate(lang, message)
  return text === message ? message : text
}
